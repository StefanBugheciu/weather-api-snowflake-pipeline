SELECT CITY, FORECAST_DATE, MIN_TEMP_C, MAX_TEMP_C, PRECIPITATION_MM
FROM WEATHER_PIPELINE_DB.ANALYTICS.DAILY_FORECAST
ORDER BY FORECAST_DATE DESC, CITY LIMIT 30;

SELECT FORECAST_DATE, CITY, MAX_TEMP_C, PRECIPITATION_MM,
       DENSE_RANK() OVER (PARTITION BY FORECAST_DATE ORDER BY MAX_TEMP_C DESC) AS WARMTH_RANK,
       DENSE_RANK() OVER (PARTITION BY FORECAST_DATE ORDER BY PRECIPITATION_MM DESC) AS RAIN_RANK
FROM WEATHER_PIPELINE_DB.ANALYTICS.DAILY_FORECAST
ORDER BY FORECAST_DATE DESC, WARMTH_RANK, CITY LIMIT 30;

SELECT CITY, FORECAST_START, COUNT(*) AS ROWS_PER_KEY
FROM WEATHER_PIPELINE_DB.RAW.FORECAST_SNAPSHOTS
GROUP BY CITY, FORECAST_START HAVING COUNT(*) > 1;

SELECT DATA_TYPE
FROM WEATHER_PIPELINE_DB.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'RAW' AND TABLE_NAME = 'FORECAST_SNAPSHOTS'
  AND COLUMN_NAME = 'PAYLOAD';

SELECT TYPEOF(PAYLOAD) AS PAYLOAD_TYPE, TYPEOF(PAYLOAD:daily.time) AS DATE_ARRAY_TYPE,
       COUNT(*) AS SNAPSHOT_COUNT
FROM WEATHER_PIPELINE_DB.RAW.FORECAST_SNAPSHOTS
GROUP BY 1, 2;

WITH OVERLAPS AS (
    SELECT r.CITY, TO_DATE(f.VALUE::VARCHAR, 'YYYY-MM-DD') AS FORECAST_DATE,
           MAX(r.FORECAST_START) AS EXPECTED_START
    FROM WEATHER_PIPELINE_DB.RAW.FORECAST_SNAPSHOTS AS r,
    LATERAL FLATTEN(INPUT => r.PAYLOAD:daily.time) AS f
    GROUP BY 1, 2
    HAVING COUNT(DISTINCT r.FORECAST_START) > 1
)
SELECT COUNT(*) AS OVERLAPPING_CITY_DAYS,
       COUNT(CASE WHEN a.FORECAST_START IS DISTINCT FROM o.EXPECTED_START THEN 1 END)
           AS WRONG_OR_MISSING_WINNERS
FROM OVERLAPS AS o
LEFT JOIN WEATHER_PIPELINE_DB.ANALYTICS.DAILY_FORECAST AS a
    ON a.CITY = o.CITY AND a.FORECAST_DATE = o.FORECAST_DATE;
