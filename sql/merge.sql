MERGE INTO WEATHER_PIPELINE_DB.RAW.FORECAST_SNAPSHOTS AS target
USING (
    SELECT %s AS CITY, TO_DATE(%s) AS FORECAST_START, TO_TIMESTAMP_TZ(%s) AS CAPTURED_AT,
           PARSE_JSON(%s) AS PAYLOAD
) AS source
ON target.CITY = source.CITY AND target.FORECAST_START = source.FORECAST_START
WHEN MATCHED AND source.CAPTURED_AT > target.CAPTURED_AT THEN
    UPDATE SET CAPTURED_AT = source.CAPTURED_AT, PAYLOAD = source.PAYLOAD
WHEN NOT MATCHED THEN
    INSERT (CITY, FORECAST_START, CAPTURED_AT, PAYLOAD)
    VALUES (source.CITY, source.FORECAST_START, source.CAPTURED_AT, source.PAYLOAD);
