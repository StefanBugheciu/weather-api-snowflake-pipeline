CREATE DATABASE IF NOT EXISTS WEATHER_PIPELINE_DB;
CREATE SCHEMA IF NOT EXISTS WEATHER_PIPELINE_DB.RAW;
CREATE SCHEMA IF NOT EXISTS WEATHER_PIPELINE_DB.ANALYTICS;

CREATE TABLE IF NOT EXISTS WEATHER_PIPELINE_DB.RAW.FORECAST_SNAPSHOTS (
    CITY VARCHAR NOT NULL,
    FORECAST_START DATE NOT NULL,
    CAPTURED_AT TIMESTAMP_TZ NOT NULL,
    PAYLOAD VARIANT NOT NULL,
    PRIMARY KEY (CITY, FORECAST_START)
);

CREATE VIEW IF NOT EXISTS WEATHER_PIPELINE_DB.ANALYTICS.DAILY_FORECAST AS
SELECT
    r.CITY,
    r.FORECAST_START,
    TO_DATE(f.VALUE::VARCHAR, 'YYYY-MM-DD') AS FORECAST_DATE,
    GET(r.PAYLOAD:daily.temperature_2m_min, f.INDEX)::FLOAT AS MIN_TEMP_C,
    GET(r.PAYLOAD:daily.temperature_2m_max, f.INDEX)::FLOAT AS MAX_TEMP_C,
    GET(r.PAYLOAD:daily.precipitation_sum, f.INDEX)::FLOAT AS PRECIPITATION_MM
FROM WEATHER_PIPELINE_DB.RAW.FORECAST_SNAPSHOTS AS r,
LATERAL FLATTEN(INPUT => r.PAYLOAD:daily.time) AS f
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY r.CITY, TO_DATE(f.VALUE::VARCHAR, 'YYYY-MM-DD')
    ORDER BY r.FORECAST_START DESC, r.CAPTURED_AT DESC
) = 1;
